#!/usr/bin/env node
/* Generates themes.css from palettes.js.  Run: node build-themes.js
   Selectors use attributes, not just :root, so any element can carry its own
   data-palette / data-mode (the settings dialog uses this for live previews). */
"use strict";
var fs = require("fs");
var path = require("path");
var P = require("./palettes.js");

function block(selector, tokens, indent) {
  indent = indent || "";
  return indent + selector + " {\n" + Object.keys(tokens).map(function (k) {
    return indent + "  --efv-" + k + ": " + tokens[k] + ";";
  }).join("\n") + "\n" + indent + "}\n";
}

// Mode-level values that do not depend on the palette.
var MODE = {
  light: {
    "scrim": "rgba(14, 22, 19, 0.38)",
    "shadow-card": "0 1px 1px rgba(0, 0, 0, 0.05)",
    "shadow-sheet": "0 0 0 1px rgba(0, 0, 0, 0.09), 0 1px 2px rgba(0, 0, 0, 0.06), 0 10px 24px -14px rgba(0, 0, 0, 0.28)",
    "shadow-pop": "0 0 0 1px rgba(0, 0, 0, 0.1), 0 12px 32px -8px rgba(0, 0, 0, 0.32)",
    "seam-opacity": "0.6"
  },
  dark: {
    "scrim": "rgba(0, 0, 0, 0.55)",
    "shadow-card": "0 0 0 1px rgba(0, 0, 0, 0.2)",
    "shadow-sheet": "0 0 0 1px rgba(0, 0, 0, 0.5), 0 12px 28px -12px rgba(0, 0, 0, 0.7)",
    "shadow-pop": "0 0 0 1px rgba(255, 255, 255, 0.07), 0 16px 40px -8px rgba(0, 0, 0, 0.7)",
    "seam-opacity": "0.75"
  }
};

var out = [];
out.push("/* GENERATED by build-themes.js from palettes.js. Do not edit by hand. */\n");
out.push("/* Root attributes: data-mode = light | dark | system, data-palette = " + P.PALETTES.map(function (p) { return p.id; }).join(" | ") + ".\n" +
  "   The email sheet (#ffffff) is deliberately NOT a theme token. */\n");

// Fallback before attributes are set: default palette, light.
var def = P.PALETTES.filter(function (p) { return p.id === P.DEFAULT_PALETTE; })[0];
out.push(block(":root", Object.assign({}, def.light, MODE.light)));

// Mode
out.push("[data-mode=\"light\"] { color-scheme: light; }\n[data-mode=\"dark\"] { color-scheme: dark; }\n");
out.push(block("[data-mode=\"light\"], [data-mode=\"system\"]", MODE.light));
out.push(block("[data-mode=\"dark\"]", MODE.dark));
out.push("@media (prefers-color-scheme: dark) {\n  [data-mode=\"system\"] { color-scheme: dark; }\n" + block("[data-mode=\"system\"]", MODE.dark, "  ") + "}\n");

// Palettes
P.PALETTES.forEach(function (p) {
  out.push("/* " + p.name.en + " / " + p.name.zh + " */\n");
  out.push(block("[data-palette=\"" + p.id + "\"]", p.light));
  out.push(block("[data-palette=\"" + p.id + "\"][data-mode=\"dark\"]", p.dark));
  out.push("@media (prefers-color-scheme: dark) {\n" + block("[data-palette=\"" + p.id + "\"][data-mode=\"system\"]", p.dark, "  ") + "}\n");
});

fs.writeFileSync(path.join(__dirname, "themes.css"), out.join("\n"));
console.log("themes.css written: " + P.PALETTES.length + " palettes x 2 modes");
